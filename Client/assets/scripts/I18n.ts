export class I18n {
    private static currentLocale: Locale = "zh-CN";

    public static init(): void {
        try {
            if (typeof localStorage !== "undefined") {
                const saved = localStorage.getItem(STORAGE_KEY);
                if (saved === "zh-CN" || saved === "en-US") {
                    this.currentLocale = saved;
                }
            }
        } catch {
            // 环境不支持 localStorage 时保持默认
        }
    }

    public static getLocale(): Locale {
        return this.currentLocale;
    }

    public static setLocale(locale: Locale): void {
        this.currentLocale = locale;
        try {
            if (typeof localStorage !== "undefined") {
                localStorage.setItem(STORAGE_KEY, locale);
            }
        } catch {
            // ignore
        }
    }

    public static t(key: string, fallback?: string): string {
        const dict = DICTIONARY[this.currentLocale] ?? DICTIONARY["zh-CN"];
        return dict[key] ?? fallback ?? key;
    }
}
