namespace RaceGame.Domain.Enums;

/// <summary>
/// 比赛轮次状态机枚举。
/// 对应数据库 race_rounds.state 字段，状态以严格递增顺序流转，禁止逆向跃迁或状态回滚。
/// </summary>
public enum RaceState
{
    /// <summary>
    /// 投注中（状态码 1）：
    /// 玩家可自由浏览当期 6 匹赛马赔率、历史战绩与胜率，并在截止时间前提交单选马匹押注订单。
    /// </summary>
    Betting = 1,

    /// <summary>
    /// 投注截止封盘（状态码 2）：
    /// 达到投注倒计时截止时刻，系统停止接受新注单，锁定所有已提交注单的赔率与本金，准备生成随机种子与黑马标记。
    /// </summary>
    Closed = 2,

    /// <summary>
    /// 赛前准备与亮相（状态码 3）：
    /// 赛马入闸、骑师就位阶段。服务端确定各马匹出场信息并通过 SignalR 推送给客户端播放赛前准备动画。
    /// </summary>
    Preparing = 3,

    /// <summary>
    /// 比赛进行中（状态码 4）：
    /// 闸门开启，比赛正式开跑。各马匹按照基于确定性种子与比赛时长缩放的完赛时间奔跑冲线，客户端播放扬鞭加速与赛跑动画。
    /// </summary>
    Racing = 4,

    /// <summary>
    /// 结算中（状态码 5）：
    /// 所有赛马完成冲线后触发。服务端在同一持久化数据库事务中核算所有注单盈亏、执行钱包本金与奖金划拨、发放角色升级奖励并扣减平台手续费。
    /// </summary>
    Settlement = 5,

    /// <summary>
    /// 比赛已结束（状态码 6）：
    /// 结算全部完成，赛果已永久归档并发布至历史记录大屏。广播中奖信息与弹幕，随后由 Worker 调度开启下一轮新比赛。
    /// </summary>
    Finished = 6,

    /// <summary>
    /// 比赛已取消（状态码 7）：
    /// 异常中断或运营干预状态。当系统检测到不可恢复的严重故障时触发，所有已扣款注单将在事务内原路全额退款至玩家钱包。
    /// </summary>
    Cancelled = 7
}